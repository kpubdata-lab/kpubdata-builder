#!/usr/bin/env python3
"""License inventory of what Builder depends on and bundles (#847).

``uv.lock`` says WHICH packages are used but not under what licence, and the MIT
``LICENSE`` of this repository says nothing about any of them. This script keeps two
things next to each other:

* ``docs/compliance/license_inventory.json`` -- one record per locked package (name,
  version, scope, license as the package declares it, source URL), bundled data group,
  and container input. Package records come from installed metadata where available.
* ``THIRD_PARTY_NOTICES.md`` -- the same facts as a readable notice, written from the
  JSON alone.

It does not judge a license. A package whose declared license is empty, comes from
another installed version, or is not one of the plainly permissive identifiers below
is listed as ``needs review`` for the maintainer; matching is a string comparison, not a legal
conclusion.

Usage::

    uv sync --locked --all-extras --no-sources
    uv run --no-sources python scripts/license_inventory.py            # rewrite both files
    uv run --no-sources python scripts/license_inventory.py --check    # fail on drift (CI)

``--check`` needs no installed packages: it compares the lock file and ``git ls-files``
with the recorded JSON, and the JSON with the notice. So a dependency added to the lock
without a recorded licence fails the gate.
"""

